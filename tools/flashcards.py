import json as _fj, html as _fh

# Fronts that the automatic rule ("text up to the first =, ⇒ or ⇔, then ?") gets wrong.
FC_FRONT = {
 "ax² + bx + c = 0": "Roots of ax² + bx + c = 0: x = ?",
 "AP: Tₙ": "AP: Tₙ and Sₙ = ?",
 "GP: Tₙ": "GP: Tₙ and Sₙ = ?",
 "log(mn)": "log(mn) and log(m/n) = ?",
 "N = pᵃ": "Number of factors of N = pᵃ qᵇ rᶜ = ?",
 "Euler:": "Euler's theorem: if gcd(a, n) = 1, then ?",
 "ⁿPᵣ": "ⁿPᵣ and ⁿCᵣ = ?",
 "Triangle: area": "Area of a triangle (two ways) = ?",
 "Circle: area": "Circle: area, circumference and sector = ?",
 "Sphere V": "Volume of a sphere, cone and cylinder; surface of a sphere = ?",
 "Boat b": "Boat speed b and stream speed s from downstream and upstream speeds = ?",
 "Rectangle area": "Rectangle: area and perimeter = ?",
 "Cube V": "Cube: volume and surface; cuboid surface = ?",
 "Cylinder CSA": "Cylinder: curved and total surface area = ?",
 "Cone slant": "Cone: slant height and curved surface area = ?",
 "A–Z positions": "EJOTY: positions of E, J, O, T and Y = ?",
 "Hands coincide": "The hands of a clock coincide every ? minutes",
 "Hands overlap": "In 24 hours, how many times do clock hands overlap, point opposite and form right angles?",
 "Days of the week repeat": "How many odd days are there in 100 years?",
 "Turning right from North": "Facing North: a right turn faces ?, a left turn faces ?",
 "A ≥ B > C": "A ≥ B > C gives ?  And A ≥ B ≤ C gives ?",
 "Some A are B": "Some A are B gives ?  And 'All A are B' gives ?",
}

def _fc_front(f):
    for k, v in FC_FRONT.items():
        if f.startswith(k): return v
    cuts = [(f.find(x), x) for x in (" ⇒ ", " ⇔ ", " = ") if x in f]
    if cuts:
        i, x = min(cuts); return f[:i + len(x)].strip() + " ?"
    if ": " in f: return f[:f.find(": ") + 1] + " ?"
    return None

FC_DECKS = []
for _s in SHEETS:
    _cards = []
    for _g, _items in _s["groups"]:
        for _fx, _nt in _items:
            _f = _fh.unescape(_fx); _q = _fc_front(_f)
            assert _q and _q != _f, ("flashcard front missing", _f)
            _cards.append({"g": _fh.unescape(_g), "q": _q, "a": _f, "n": _fh.unescape(_nt)})
    _name = _fh.unescape(_s["h1"]).replace(" formula sheet", "").replace(" shortcuts sheet", "")
    FC_DECKS.append({"id": _s["slug"], "name": _name, "sheet": f"formula-{_s['slug']}.html", "cards": _cards})
assert len({d["id"] for d in FC_DECKS}) == len(FC_DECKS)
open("assets/js/flashcards-data.js", "w").write("/* Generated by tools/flashcards.py from tools/sheets.py. Do not edit by hand. */\nwindow.FC_DECKS = "
    + _fj.dumps(FC_DECKS, ensure_ascii=False, separators=(",", ":")) + ";\n")
FC_TOTAL = sum(len(d["cards"]) for d in FC_DECKS)

_esc2 = lambda s: _fh.escape(s, quote=False)
_fc_list = "".join(f'<h3>{_esc2(d["name"])}</h3><ul class="fc-list">' + "".join(
    f'<li><span class="fc-list-q">{_esc2(c["q"])}</span> <span class="fs-f">{_esc2(c["a"])}</span>' + (f' <span class="muted">{_esc2(c["n"])}</span>' if c["n"] else "") + "</li>"
    for c in d["cards"]) + "</ul>" for d in FC_DECKS)
