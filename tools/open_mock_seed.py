"""Generate the Open Mock schedule (data/open-mock.json) and the Supabase seed migration with the hidden answer key.
Open Mock = first Sunday of each month, 10:00-22:00 IST. Edit SCHEDULE, then run: python3 tools/open_mock_seed.py
"""
import json, datetime as dt
IST = dt.timezone(dt.timedelta(hours=5, minutes=30))
def first_sunday(y, m):
    d = dt.date(y, m, 1); return d + dt.timedelta(days=(6 - d.weekday()) % 7)
# (month id, pack). Only packs that exist in data/cat/*.json. 2026-11 reuses CAT Mock 5, which is already public on mock-tests.html.
SCHEDULE = [("2026-11", "mock-5")]
SECS = ["varc", "dilr", "qa"]
bank = {s: json.load(open(f"data/cat/{s}.json", encoding="utf8"))["questions"] for s in SECS}
out, sql = [], ["-- GENERATED by tools/open_mock_seed.py. Do not edit by hand.", "-- Open Mock schedule + hidden answer key (open_mock_keys has no client grants)."]
q = lambda v: "'" + str(v).replace("'", "''") + "'"
for mid, pack in SCHEDULE:
    y, m = map(int, mid.split("-")); day = first_sunday(y, m)
    st = dt.datetime.combine(day, dt.time(10, 0), IST); en = dt.datetime.combine(day, dt.time(22, 0), IST)
    title = f"AptiSetu Open Mock · {day.strftime('%B %Y')}"
    counts = {}
    sql.append(f"insert into public.open_mocks (id, title, pack, starts_at, ends_at) values ({q(mid)}, {q(title)}, {q(pack)}, {q(st.isoformat())}, {q(en.isoformat())}) on conflict (id) do update set title = excluded.title, pack = excluded.pack, starts_at = excluded.starts_at, ends_at = excluded.ends_at;")
    sql.append(f"delete from public.open_mock_keys where mock_id = {q(mid)};")
    for s in SECS:
        qs = [x for x in bank[s] if x.get("pack") == pack]; assert qs, (pack, s); counts[s] = len(qs)
        rows = ",\n  ".join(f"({q(mid)}, {q(s)}, {q(x['id'])}, {q(x['type'])}, {q(x.get('kind', ''))}, {q(x['answer'])})" for x in qs)
        sql.append(f"insert into public.open_mock_keys (mock_id, section, qid, qtype, kind, answer) values\n  {rows};")
    out.append({"id": mid, "title": title, "pack": pack, "date": day.isoformat(), "starts_at": st.isoformat(), "ends_at": en.isoformat(), "questions": counts, "reused_public_mock": True})
json.dump({"mocks": out}, open("data/open-mock.json", "w", encoding="utf8"), ensure_ascii=False, indent=1)
open("supabase/migrations/20261028000004_open_mock_seed.sql", "w", encoding="utf8").write("\n".join(sql) + "\n")
print("open mocks:", [(o["id"], o["date"], o["pack"], o["questions"]) for o in out])
