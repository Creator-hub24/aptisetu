"""Generate the Open Mock schedule (data/open-mock.json) and the Supabase seed migration with the hidden answer key.
Open Mock = every Sunday, 10:00-22:00 IST. Edit SCHEDULE, then run: python3 tools/open_mock_seed.py

Two kinds of edition:
* REUSED pack (already in data/cat/*.json and on mock-tests.html): the key goes in the migration file, as before.
  Those answers are public anyway.
* SEALED pack (a fresh mock, listed in SEALED): this repository is public and GitHub Pages serves every file in it,
  so nothing with an answer or a solution may be committed before the edition ends. The full pack (answers and
  solutions) lives only in the git-ignored folder private/. From it this script writes
    - data/open/<pack>.<section>.json   questions only, NO answers, NO solutions (served to the browser), and
    - private/sql/<migration>_KEY_PRIVATE.sql         the key and solutions for public.open_mock_keys. Run it by hand in the
                                        Supabase SQL Editor. Never commit it.
  The committed migration for a sealed edition holds only the schedule row. If private/ is not on this machine the
  script leaves the existing question files alone and skips the key file.
"""
import json, os, datetime as dt
IST = dt.timezone(dt.timedelta(hours=5, minutes=30))
def first_sunday(y, m):
    d = dt.date(y, m, 1); return d + dt.timedelta(days=(6 - d.weekday()) % 7)
# (id, pack, ranked, date or None, migration file, special label or None). Reused packs must exist in data/cat/*.json.
# date None = first Sunday of the month in a YYYY-MM id (legacy monthly editions). New weekly editions must pass an explicit Sunday date.
# Each edition gets its OWN migration file: `supabase db push` never
# re-runs a file it has already applied, so a new edition added to an old file would not reach the database.
# 2026-11 reused CAT Mock 5 and 2026-11-15 (extra pre-CAT edition) reuses CAT Mock 4; both are already public on
# mock-tests.html, so they are UNRANKED practice (no leaderboard; migration 20261030000006 closes the leaderboard RPCs).
# 2026-11-22 uses mock-6, a new mock that is not on mock-tests.html or in any practice listing. Still unranked.
SCHEDULE = [("2026-11", "mock-5", False, None, "20261028000004_open_mock_seed.sql", None),
            ("2026-11-15", "mock-4", False, "2026-11-15", "20261111000007_open_mock_2026_11_15.sql", "Pre-CAT edition"),
            ("2026-11-22", "mock-6", False, "2026-11-22", "20261113000010_open_mock_2026_11_22.sql", None)]
SEALED = {"mock-6": "private/mock6"}      # pack -> git-ignored folder holding <pack>.<section>.json with answers
PUBLIC_FIELDS = ("id", "exam", "section", "topic", "difficulty", "question", "set", "type", "kind", "options")   # never answer/solution
SECS = ["varc", "dilr", "qa"]
bank = {s: json.load(open(f"data/cat/{s}.json", encoding="utf8"))["questions"] for s in SECS}
out, HEAD = [], ["-- GENERATED by tools/open_mock_seed.py. Do not edit by hand."]
q = lambda v: "'" + str(v).replace("'", "''") + "'"
for mid, pack, ranked, date, mig, special in SCHEDULE:
    sealed = pack in SEALED
    day = dt.date.fromisoformat(date) if date else first_sunday(*map(int, mid.split("-")))
    assert day.weekday() == 6, (mid, "not a Sunday")
    st = dt.datetime.combine(day, dt.time(10, 0), IST); en = dt.datetime.combine(day, dt.time(22, 0), IST)
    title = (f"AptiSetu Open Mock · {special}, {day.day} {day.strftime('%B %Y')}" if special else
             f"AptiSetu Open Mock · {day.day} {day.strftime('%B %Y')}" if date else f"AptiSetu Open Mock · {day.strftime('%B %Y')}")
    counts = {}
    sched = f"insert into public.open_mocks (id, title, pack, starts_at, ends_at) values ({q(mid)}, {q(title)}, {q(pack)}, {q(st.isoformat())}, {q(en.isoformat())}) on conflict (id) do update set title = excluded.title, pack = excluded.pack, starts_at = excluded.starts_at, ends_at = excluded.ends_at;"
    if not sealed:
        sql = HEAD + ["-- Open Mock schedule + hidden answer key (open_mock_keys has no client grants).", sched, f"delete from public.open_mock_keys where mock_id = {q(mid)};"]
        for s in SECS:
            qs = [x for x in bank[s] if x.get("pack") == pack]; assert qs, (pack, s); counts[s] = len(qs)
            rows = ",\n  ".join(f"({q(mid)}, {q(s)}, {q(x['id'])}, {q(x['type'])}, {q(x.get('kind', ''))}, {q(x['answer'])})" for x in qs)
            sql.append(f"insert into public.open_mock_keys (mock_id, section, qid, qtype, kind, answer) values\n  {rows};")
    else:
        assert not any(x.get("pack") == pack for s in SECS for x in bank[s]), (pack, "is sealed but is in the public bank")
        src = SEALED[pack]; have = all(os.path.exists(f"{src}/{pack}.{s}.json") for s in SECS)
        sql = HEAD + [f"-- Open Mock schedule for {mid} ({pack}: a sealed pack).",
                      "-- The answer key and solutions are NOT in this file or anywhere in the repository, because the repository is public.",
                      f"-- They are in private/sql/{mig.replace(".sql", "_KEY_PRIVATE.sql")} (git-ignored); run that file by hand in the Supabase SQL Editor after this one",
                      "-- and after 20261113000009_open_mock_sealed_review.sql.", sched]
        key = HEAD + [f"-- PRIVATE: answer key and solutions for Open Mock {mid} ({pack}). Never commit or publish before the edition ends.",
                      "-- Run in the Supabase SQL Editor AFTER 20261113000009_open_mock_sealed_review.sql.", sched,
                      f"delete from public.open_mock_keys where mock_id = {q(mid)};"]
        os.makedirs("data/open", exist_ok=True)
        for s in SECS:
            if have:
                d = json.load(open(f"{src}/{pack}.{s}.json", encoding="utf8")); qs = d["questions"]
                pub = {"name": d["name"], "pack": pack, "sealed": True,
                       "questions": [{**{k: x[k] for k in PUBLIC_FIELDS if k in x}, "pack": pack} for x in qs], "sets": d["sets"]}
                blob = json.dumps(pub, ensure_ascii=False, indent=1)
                assert '"answer"' not in blob and '"solution"' not in blob
                open(f"data/open/{pack}.{s}.json", "w", encoding="utf8").write(blob)
                rows = ",\n  ".join(f"({q(mid)}, {q(s)}, {q(x['id'])}, {q(x['type'])}, {q(x.get('kind', ''))}, {q(x['answer'])}, {q(x['solution'])})" for x in qs)
                key.append(f"insert into public.open_mock_keys (mock_id, section, qid, qtype, kind, answer, solution) values\n  {rows};")
            else:
                qs = json.load(open(f"data/open/{pack}.{s}.json", encoding="utf8"))["questions"]
            counts[s] = len(qs)
        if have:
            os.makedirs("private/sql", exist_ok=True)
            open("private/sql/" + mig.replace(".sql", "_KEY_PRIVATE.sql"), "w", encoding="utf8").write("\n".join(key) + "\n")
        else: print(f"NOTE: {src} not found, so the key file for {mid} was not written (question files left as they are).")
    label = ("Ranked" if ranked else "Unranked practice") + ", " + ("new questions" if sealed else pack.replace("mock-", "Mock ") + " questions")
    out.append({"id": mid, "title": title, "pack": pack, "date": day.isoformat(), "starts_at": st.isoformat(), "ends_at": en.isoformat(), "questions": counts,
                "reused_public_mock": not sealed, **({"sealed": True} if sealed else {}),
                "ranked": ranked, **({"special": special} if special else {}), "label": label})
    open("supabase/migrations/" + mig, "w", encoding="utf8").write("\n".join(sql) + "\n")
json.dump({"mocks": out}, open("data/open-mock.json", "w", encoding="utf8"), ensure_ascii=False, indent=1)
print("open mocks:", [(o["id"], o["date"], o["pack"], o["questions"]) for o in out])
